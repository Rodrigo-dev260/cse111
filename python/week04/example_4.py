# Example 4
def main():
    # Count from zero to nine by one.
    for i in range(10):
        print(i)
    print()
    # Count from five to nine by one.
    for i in range(5,10):
        print(i)
    print()
    # Count from zero to eight by two.
    for i in range(0, 10, 2):
        print(i)
    print()
    # Count From 100, 69, -3
    for i in range(100, 69, -3):
        print(i)
# Call main to start thi program.
if __name__ == '__main__':
    main()
    
         
